#!/bin/sh
# gen-software-docs.sh: writes the two software pages of the docs from the recipes.
#   docs/software-guide.md  what the main software is for, by area: the areas and the package
#                           names come from docs/software-categories.txt (edit that file), the
#                           version, summary and home page of each package from its recipe.
#   docs/software-index.md  every package in packages/, alphabetically, with version and summary.
# Run from anywhere:  sh tools/gen-software-docs.sh
# A name in the categories file that has no recipe is reported on stderr (and marked in the page).
set -eu

root=$(cd "$(dirname "$0")/.." && pwd)
cd "$root"
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

# name<TAB>version<TAB>release<TAB>summary<TAB>homepage, from the top of each recipe (before its
# first [table]); recipes are packages/<letter>/<name>/package.toml
for f in packages/*/*/package.toml; do
    awk '
        /^\[/ { exit }
        /^name *= *"/     { sub(/^name *= *"/, ""); sub(/".*/, ""); name = $0 }
        /^version *= *"/  { sub(/^version *= *"/, ""); sub(/".*/, ""); ver = $0 }
        /^release *= *[0-9]/ { sub(/^release *= */, ""); rel = $0 }
        /^summary *= *"/  { sub(/^summary *= *"/, ""); sub(/"[ \t]*$/, ""); sum = $0 }
        /^homepage *= *"/ { sub(/^homepage *= *"/, ""); sub(/".*/, ""); home = $0 }
        END { if (name != "") printf "%s\t%s\t%s\t%s\t%s\n", name, ver, rel, sum, home }
    ' "$f"
done | LC_ALL=C sort -t "	" -k1,1 > "$tmp/packages.tsv"

total=$(wc -l < "$tmp/packages.tsv")

# ---- the full index
{
    echo "# Software index"
    echo
    echo "Every package in the tree (\`packages/\`), $total in all, with its version and what it is. Generated by"
    echo "\`tools/gen-software-docs.sh\` from the recipes: do not edit by hand. For what the main"
    echo "software is for, by area, see [software-guide.md](software-guide.md)."
    echo
    awk -F "	" '
        {
            c = toupper(substr($1, 1, 1))
            if (c !~ /[A-Z]/) c = "0-9"
            if (c != last) { printf "\n## %s\n\n| Package | Version | What it is |\n|---|---|---|\n", c; last = c }
            s = $4; gsub(/\|/, "\\|", s)
            printf "| %s | %s | %s |\n", $1, $2, s
        }
    ' "$tmp/packages.tsv"
} > docs/software-index.md

# ---- the guide
{
    echo "# Software guide"
    echo
    echo "What the main software in the tree is for, by area: a reminder when planning a home lab or a"
    echo "small-business server. The areas and the names are in \`docs/software-categories.txt\`; the"
    echo "version and the one-line description of each package are read from its recipe. Generated by"
    echo "\`tools/gen-software-docs.sh\`: do not edit by hand. Every package in the tree is listed in"
    echo "[software-index.md](software-index.md)."
    echo
    echo "Server packages are **inert**: installing one enables no service, opens no port and sets up"
    echo "no site or cron job (the package's \`README.FenrirOS\`, where there is one, says how to set"
    echo "it up; some apps create their own first-run login, which the README names). Services start"
    echo "with dinit: \`dinitctl start NAME\`; to run one at every boot, link it into"
    echo "\`/etc/dinit.d/boot.d\`. A recipe in the tree is not necessarily built yet: see"
    echo "[roadmap.md](roadmap.md) for the state of things."
    awk -F "	" -v tsv="$tmp/packages.tsv" '
        BEGIN {
            while ((getline line < tsv) > 0) {
                split(line, a, "\t")
                ver[a[1]] = a[2]; rel[a[1]] = a[3]; sum[a[1]] = a[4]; home[a[1]] = a[5]
            }
            FS = "\n"
        }
        /^## / { sub(/^## /, ""); printf "\n## %s\n\n", $0; intable = 0; next }
        /^- / {
            line = $0; sub(/^- /, "", line)
            n = split(line, parts, " \\| ")
            name = parts[1]; note = (n > 1) ? parts[2] : ""
            if (!intable) { printf "\n| Package | Version | What it is | Used for |\n|---|---|---|---|\n"; intable = 1 }
            if (name in ver) {
                s = sum[name]; gsub(/\|/, "\\|", s)
                h = home[name]
                label = (h != "") ? "[" name "](" h ")" : name
                printf "| %s | %s | %s | %s |\n", label, ver[name], s, note
            } else {
                printf "| %s | - | (not in the tree) | %s |\n", name, note
                print "gen-software-docs: no recipe named " name > "/dev/stderr"
            }
            next
        }
        { print }
    ' docs/software-categories.txt
} > docs/software-guide.md

echo "wrote docs/software-guide.md and docs/software-index.md ($total packages)"
